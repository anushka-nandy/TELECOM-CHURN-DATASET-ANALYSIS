--NO OF CUSTOMERS
SELECT COUNT (CUSTOMER_ID ) FROM CUSTOMER_CHURN AS NO_OF_CUSTOMERS;

--SUM OF CHURN
SELECT COUNT(CHURN) FROM CUSTOMER_CHURN AS NO_OF_CHURN;

--CHECK WHETHER THE DATA IS CLEAN 
SELECT COUNT(*) AS TOTAL_ROWS, COUNT (DISTINCT CUSTOMER_ID) AS UNIQUE_IDS,
       COUNT(*) FILTER(WHERE TOTAL_CHARGES IS NULL) AS BLANK_TOTAL_CHARGES,
	   COUNT(*) FILTER(WHERE TENURE=0) AS TENURE_ZERO FROM CUSTOMER_CHURN;

--TOTAL CUSTOMER IN EACH TELECOM PARTNER
SELECT TELECOM_PARTNER, COUNT(CUSTOMER_ID) FROM TELECOM_CHURN
GROUP BY TELECOM_PARTNER ORDER BY COUNT(CUSTOMER_ID) DESC;

--TOTAL CUSTOMERS IN EACH CITY
SELECT COUNT (CUSTOMER_ID) AS NO_OF_CUSTOMERS_PER_CITY, CITY FROM TELECOM_CHURN
GROUP BY CITY ORDER BY NO_OF_CUSTOMERS_PER_CITY DESC;

--5 STATE WITH MOST CUSTOMERS
SELECT COUNT (CUSTOMER_ID) AS NO_OF_CUSTOMERS_PER_STATE, STATE FROM TELECOM_CHURN
GROUP BY STATE ORDER BY NO_OF_CUSTOMERS_PER_STATE DESC 
LIMIT 5;

--CREATING AN AGE PROFILE
SELECT CASE
WHEN AGE <=25 THEN '18-25'
WHEN AGE <=35 THEN '26-35'
WHEN AGE <=45 THEN '36-45'
WHEN AGE <=55 THEN '46-55'
ELSE '56+' 
END AS AGE_PROFILE,
COUNT (CUSTOMER_ID) AS CUSTOMER_IN_EACH_AGE_GROUP FROM TELECOM_CHURN
GROUP BY AGE_PROFILE;

--GENDER SPLIT
SELECT GENDER, COUNT(CUSTOMER_ID) AS NO_OF_CUSTOMERS_GENDERWISE
FROM TELECOM_CHURN
GROUP BY GENDER ORDER BY NO_OF_CUSTOMERS_GENDERWISE DESC;

--NO. OF CUSTOMERS JOINED EACH YEAR
SELECT EXTRACT(YEAR FROM REGISTRATION_DATE) AS REGISTRATION_PER_YEAR, 
COUNT (CUSTOMER_ID) AS NO_OF_CUSTOMERS_YEARWISE FROM TELECOM_CHURN
GROUP BY REGISTRATION_PER_YEAR;

--WHAT TYPE OF CONTRACTS DO CUSTOMERS HAVE?
SELECT CONTRACT, COUNT(CUSTOMER_ID) AS NO_OF_CUSTOMERS_CONTRACTWISE
FROM CUSTOMER_CHURN
GROUP BY CONTRACT ORDER BY NO_OF_CUSTOMERS_CONTRACTWISE DESC;

--WHICH INTERNET SERVICE IS MOST COMMON?
SELECT INTERNET_SERVICE, COUNT(CUSTOMER_ID) AS NO_OF_CUSTOMERS_INTERNETWISE
FROM CUSTOMER_CHURN
GROUP BY INTERNET_SERVICE ORDER BY NO_OF_CUSTOMERS_INTERNETWISE DESC;

--HOW DO CUSTOMERS PAY?
SELECT PAYMENT_METHOD, COUNT(CUSTOMER_ID) AS NO_OF_CUSTOMERS_PAYMENTWISE
FROM CUSTOMER_CHURN
GROUP BY PAYMENT_METHOD ORDER BY NO_OF_CUSTOMERS_PAYMENTWISE DESC;

--WHAT DO CUSTOMERS PAY EACH MONTH?
SELECT MONTHLY_CHARGES, COUNT(CUSTOMER_ID) AS PAYMENT_EACH_MONTH
FROM CUSTOMER_CHURN 
GROUP BY MONTHLY_CHARGES ORDER BY PAYMENT_EACH_MONTH DESC;